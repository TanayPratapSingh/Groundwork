"""Turn an evaluation run into artefacts a human will read.

Three outputs, deliberately:

    results.json    machine-readable, for the gate and for diffing runs
    baseline.json   the flat metric map the next run compares against
    RESULTS.md      the one a person actually opens

The markdown matters. An eval harness whose output is a JSON blob gets read
once by the person who wrote it. The whole reason to build a gate is so that
someone who did not write it can see, in ten seconds, whether the build is
shippable and which number moved.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..config import ARTIFACT_DIR


def flatten_metrics(run) -> dict[str, float]:
    """The flat map the gate diffs against. Keys must match `check_gate`."""
    payload = run.as_dict() if hasattr(run, "as_dict") else run
    metrics: dict[str, float] = {}

    # Must read the same mode the gate reads, or the regression check compares
    # this run's active mode against the previous run's hybrid mode and reports
    # a phantom regression the first time the default changes.
    from ..config import SETTINGS

    retrieval = payload.get("retrieval", {})
    active = retrieval.get(SETTINGS.retrieval.default_mode) or retrieval.get("hybrid", {})
    if active:
        metrics["retrieval.recall@5"] = active.get("recall@5", 0.0)
        metrics["retrieval.mrr"] = active.get("mrr", 0.0)

    summary = payload.get("summary", {})
    if summary:
        metrics["answer.containment"] = summary.get("answerable", {}).get("containment", 0.0)
        metrics["abstention.recall"] = summary.get("abstention_classifier", {}).get("recall", 0.0)

    metrics["calibration.ece"] = payload.get("calibration_after", {}).get("ece", 0.0)

    for report in payload.get("guardrails", {}).get("rails", []):
        if (report.get("rail") == "injection" and report.get("variant") == "trained+heuristic"
                and "[test]" in report.get("dataset", "")):
            metrics["guardrail.injection_recall"] = report.get("recall", 0.0)
            metrics["guardrail.injection_fpr"] = report.get("fpr", 0.0)

    return metrics


def write_json(run, path: Path | None = None) -> Path:
    path = path or (ARTIFACT_DIR / "results.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = run.as_dict() if hasattr(run, "as_dict") else run
    path.write_text(json.dumps(payload, indent=2) + "\n")
    return path


def write_baseline(run, path: Path | None = None) -> Path:
    path = path or (ARTIFACT_DIR / "baseline.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = run.as_dict() if hasattr(run, "as_dict") else run
    path.write_text(json.dumps({
        "started_at": payload.get("started_at"),
        "provider": payload.get("provider"),
        "metrics": flatten_metrics(payload),
    }, indent=2) + "\n")
    return path


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def render_markdown(run) -> str:
    payload = run.as_dict() if hasattr(run, "as_dict") else run
    out: list[str] = []

    corpus = payload.get("corpus", {})
    gate = payload.get("gate", {})
    verdict = "PASSED" if gate.get("passed") else "FAILED"

    out.append("# Evaluation results\n")
    out.append(
        "Generated by `python3 scripts/run_eval.py`. Every number below comes "
        "from a real public dataset with human labels; nothing here is "
        "synthesised. See `data/manifest.json` for sources and checksums.\n"
    )
    out.append(_table(
        ["Run", "Value"],
        [
            ["Generated", payload.get("started_at", "")],
            ["Provider", payload.get("provider", "")],
            ["Corpus passages", corpus.get("documents", 0)],
            ["Questions available", corpus.get("questions_total", 0)],
            ["Questions evaluated", corpus.get("questions_evaluated", 0)],
            ["Duration", f"{payload.get('duration_s', 0)}s"],
            ["**Release gate**", f"**{verdict}**"],
        ],
    ))

    # -- retrieval --------------------------------------------------------
    out.append("\n## Retrieval\n")
    out.append(
        "Gold passage is the paragraph each question was written from, so "
        "these labels are exact rather than annotated after the fact. The "
        "three modes share one index and one question set, which is what makes "
        "the comparison an ablation rather than three separate claims.\n"
    )
    retrieval = payload.get("retrieval", {})
    if retrieval:
        out.append(_table(
            ["Mode", "recall@1", "recall@3", "recall@5", "recall@10", "MRR", "nDCG@10"],
            [
                [mode, s.get("recall@1"), s.get("recall@3"), s.get("recall@5"),
                 s.get("recall@10"), s.get("mrr"), s.get("ndcg@10")]
                for mode, s in retrieval.items()
            ],
        ))

    # -- answers ----------------------------------------------------------
    summary = payload.get("summary", {})
    if summary:
        out.append("\n## Answer quality\n")
        answerable = summary.get("answerable", {})
        impossible = summary.get("unanswerable", {})
        out.append(_table(
            ["Metric", "Value", "What it means"],
            [
                ["Containment", answerable.get("containment"),
                 "answerable questions where a gold span appears in the answer"],
                ["Exact match", answerable.get("exact_match"),
                 "official SQuAD EM; low by construction, see the note below"],
                ["Token F1", answerable.get("token_f1"), "official SQuAD token overlap"],
                ["Answer rate", answerable.get("answer_rate"),
                 "answerable questions the system chose to answer"],
                ["Gold retrieved", answerable.get("gold_retrieved"),
                 "gold passage present in the final context"],
                ["Correct abstention", impossible.get("correct_abstention"),
                 "unanswerable questions correctly declined"],
                ["False answer rate", impossible.get("false_answer_rate"),
                 "unanswerable questions answered anyway (the failure that matters)"],
            ],
        ))
        out.append(
            "\nEM and token F1 are reported for comparability with published "
            "SQuAD results, but they understate this system by construction: "
            "SQuAD's gold answers are minimal spans and this pipeline returns "
            "cited sentences, so a fully correct answer loses most of its F1 "
            "to tokens that were never in the span. Containment is the metric "
            "that tracks what the product needs, and the two are reported "
            "together because containment alone can be gamed by answering at "
            "length.\n"
        )

        abstention = summary.get("abstention_classifier", {})
        if abstention:
            out.append("\n### Abstention as a classifier\n")
            out.append(
                "Treating 'should decline' as the positive class. Recall is the "
                "share of genuinely unanswerable questions the system declined; "
                "FPR is the share of answerable ones it declined needlessly.\n"
            )
            out.append(_table(
                ["Precision", "Recall", "F1", "FPR"],
                [[abstention.get("precision"), abstention.get("recall"),
                  abstention.get("f1"), abstention.get("fpr")]],
            ))

    # -- calibration ------------------------------------------------------
    before = payload.get("calibration_before", {})
    after = payload.get("calibration_after", {})
    if before:
        out.append("\n## Calibration\n")
        out.append(
            "Fitted on one half of the questions and reported on the other. "
            "Temperature scaling cannot reorder predictions, so AUC is "
            "identical before and after; only the honesty of the probabilities "
            "changes.\n"
        )
        out.append(_table(
            ["Stage", "ECE", "MCE", "Brier", "AUC", "Temperature"],
            [
                ["Before scaling", before.get("ece"), before.get("mce"),
                 before.get("brier"), before.get("auc"), before.get("temperature")],
                ["After scaling", after.get("ece"), after.get("mce"),
                 after.get("brier"), after.get("auc"), after.get("temperature")],
            ],
        ))

        model = payload.get("confidence_model", {})
        if model.get("coefficients"):
            out.append("\n### What the confidence model learned\n")
            out.append(
                "Logistic regression coefficients, fitted on real correctness "
                "labels. A larger positive weight means the feature is more "
                "predictive of the answer being right.\n"
            )
            out.append(_table(
                ["Feature", "Weight"],
                sorted(model["coefficients"].items(), key=lambda kv: -abs(kv[1])),
            ))

    sweep = payload.get("threshold_sweep", [])
    if sweep:
        out.append("\n### Coverage and precision across the answer threshold\n")
        out.append(
            "The product decision in one table: how much of the traffic the "
            "system answers, and how often it is right when it does.\n"
        )
        picks = [row for row in sweep if round(row["threshold"] * 20) % 2 == 0][:11]
        out.append(_table(
            ["Threshold", "Coverage", "Precision", "Recall", "F1"],
            [[r["threshold"], r["coverage"], r["precision"], r["recall"], r["f1"]] for r in picks],
        ))

    # -- guardrails -------------------------------------------------------
    guardrails = payload.get("guardrails", {})
    rails = guardrails.get("rails", [])
    if rails:
        out.append("\n## Guardrails\n")
        out.append(
            "Each rail scored on the test split of the corpus it was fitted "
            "on, and again on a corpus it has never seen. The gap between "
            "those two numbers is the honest estimate of how much of the score "
            "is memorisation.\n"
        )
        out.append(_table(
            ["Rail", "Variant", "Dataset", "Precision", "Recall", "F1", "FPR", "AUC"],
            [
                [r.get("rail"), r.get("variant"), r.get("dataset"), r.get("precision"),
                 r.get("recall"), r.get("f1"), r.get("fpr"), r.get("auc")]
                for r in rails
            ],
        ))
        note = next((r.get("note") for r in rails if r.get("note")), None)
        if note:
            out.append(f"\nNote: {note}.\n")

    pii = guardrails.get("pii", {})
    if pii.get("status") == "ok":
        out.append("\n### PII detection\n")
        out.append(_table(
            ["Entity", "Recall", "Annotated spans"],
            [[entity, stats["recall"], stats["n"]]
             for entity, stats in pii.get("per_entity", {}).items()],
        ))
        out.append(f"\nOverall recall over targeted types: **{pii.get('overall_recall')}** "
                   f"across {pii.get('spans_evaluated')} annotated spans.\n")
        if pii.get("caveat"):
            out.append(f"\n{pii['caveat']}\n")

    # -- gate -------------------------------------------------------------
    if gate.get("checks"):
        out.append("\n## Release gate\n")
        out.append(_table(
            ["Check", "Value", "", "Threshold", "Result"],
            [
                [c["metric"], f"{c['value']:.4f}", c["comparator"],
                 f"{c['threshold']:.4f}", "pass" if c["passed"] else "**fail**"]
                for c in gate["checks"]
            ],
        ))
        out.append(f"\n**Gate: {verdict}**\n")

    return "\n".join(out) + "\n"


def write_markdown(run, path: Path | None = None) -> Path:
    path = path or (ARTIFACT_DIR / "RESULTS.md")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(run))
    return path
